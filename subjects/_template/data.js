Drill.setup({
  title: "科目名",
  subtitle: "試験名・範囲",
  footer: "○○の資料に基づく自習用ページ",
  storageKey: "my-subject-v1",          // 科目ごとに別の値にする（成績の保存先）
  sections: {                          // 節ID: 表示名（この順で並ぶ）
    "1.1": "1.1 はじめの節",
    "1.2": "1.2 つぎの節",
  },
  sources: {                           // 出典ID: 表示名（1種類だけなら絞り込み欄は出ない）
    slide: "スライドの問題",
    orig: "オリジナル",
    past: "過去問",
  },
  // ホームのボタン。文字列は組み込み、オブジェクトは絞り込み条件つきの独自ボタン
  quick: [
    "mix",
    { label: "スライドの問題", desc: "資料の順に全部", srcs: ["slide"], count: 0, order: "seq" },
    "past", "terms", "drill", "essay", "weak",   // "past" は過去問があるときだけ出る
  ],
});
const { source, past, mc, tf, inp, fill, calc, ord, match, essay, terms, generators, summary } = Drill;
const { rnd, pick, fmt } = Drill.util;

// ---------------------------------------------------------------------
// 問題（引数は「節, 問題文, 形式ごとの中身, 解説」の順）
// ---------------------------------------------------------------------
source("slide");

// 選択：正解は 0 始まりの番号。3択以上は自動でシャッフル（{fixed:true} で固定）
mc("1.1", "日本の首都はどこか。", ["大阪", "東京", "京都", "札幌"], 1, "1868年に江戸が東京と改称された。");

// ○×：true が ○
tf("1.1", "水は 1 気圧で 100℃ で沸騰する。", true);

// 単語入力：別解は配列で。全角半角・ひらカタ・空白・（括弧書き）は自動で吸収
inp("1.1", "HTTP の正式名称は？", ["HyperText Transfer Protocol", "ハイパーテキスト転送プロトコル"]);

source("orig");

// 穴埋め：問題文中の［A］と [ラベル, 正解 or 正解の配列] を対応させる
fill("1.2", "光の三原色は［A］・［B］・［C］である。", [["A", "赤"], ["B", ["緑", "グリーン"]], ["C", "青"]]);

// 計算：誤差 0.5% まで正解。設問は複数可
calc("1.2", "時速 60km で 2.5 時間走った。", [{ label: "走った距離", ans: 150, unit: "km" }], "60 × 2.5 = 150");

// 並べ替え：正しい順に書く（出題時にシャッフル）
ord("1.2", "小さい順に並べよ。", ["KB", "MB", "GB", "TB"]);

// 対応付け：ans[i] = left[i] に対応する right の番号
match("1.2", "左右を対応付けよ。", ["ping", "tracert"], ["経路を調べる", "到達性を確認する"], [1, 0]);

// 表とコード：問題文・解説・模範解答では「|」で始まる行が表（1行目が見出し）、`…` がコードになる。
// 「|#名前」で表に名前を付けられ、続けて書いた表は横に並ぶ。表の列数は check で検査される
mc("1.2", "|#R\n|A|B\n|1|x\n|2|y\n|#S\n|A|B\n|2|y\n|3|z\n`SELECT * FROM R UNION SELECT * FROM S;` の行数は？", ["3行", "4行", "2行", "1行"], 0,
  "(2, y) が重複するので 2＋2−1＝3 行。\n|#結果\n|A|B\n|1|x\n|2|y\n|3|z");

// 記述：模範解答とキーワード（含まれた語が緑になる）→ 自己採点
essay("1.2", "VLAN を使う利点を説明せよ。", "物理的な配線を変えずに、ネットワークを論理的に分割できる。", ["物理", "論理", "分割"]);

// 過去問：past("試験名") 以降の問題に過去問の印が付く（past(null) で解除）。形式は自由。
// ホームの「過去問」ボタンと「本番形式で通す」（時間と正答率を記録）に出る。minutes は制限時間の初期値
source("past");
past("2025年度 期末", { minutes: 50 });
mc("1.1", "【過去問】TCP/IP のトランスポート層のプロトコルはどれか。", ["IP", "TCP", "HTTP", "Ethernet"], 1);
essay("1.2", "【過去問】スループットについて、「単位時間」を使って説明せよ。", "単位時間あたりに処理・転送できるデータ量。", ["単位時間"]);
past(null);

// ---------------------------------------------------------------------
// 用語集 [節, 用語, 説明, 別解[]]  → 用語集ページ＋「説明→用語」の入力・選択問題を自動生成
// 説明文に用語そのものを書かない（check で警告が出る）
// ---------------------------------------------------------------------
terms([
  ["1.1", "プロトコル", "通信するときの決まりごと（約束事）", ["通信規約"]],
  ["1.1", "帯域", "周波数の範囲。単位はヘルツ", []],
  ["1.2", "スループット", "単位時間あたりに処理できるデータ量", []],
  ["1.2", "レイテンシ", "データを送ってから届くまでの遅れ時間", ["遅延"]],
]);

// ---------------------------------------------------------------------
// 数値ランダム問題：fn() が毎回ちがう数値で問題オブジェクトを返す（計算ドリルで無限出題）
// ---------------------------------------------------------------------
generators([
  { ch: "1.2", name: "速さ×時間", fn() {
    const v = pick([40, 50, 60, 80]), t = rnd(2, 6);
    return { type: "calc", q: `時速 ${v}km で ${t} 時間走ると何 km 進むか。`,
      parts: [{ label: "距離", ans: v * t, unit: "km" }], exp: `${v} × ${t} = ${fmt(v * t)} km` };
  } },
]);

// ---------------------------------------------------------------------
// まとめ：HTML で書く。[[語]] が赤字になり「赤シート」で隠せる
// 使えるクラス：note（補足）/ formula（公式）/ flow（番号付きの流れ。<ol class="flow">）
// ---------------------------------------------------------------------
summary([
  { ch: "1.1", title: "1.1.1 基本", body: `
<ul>
<li>[[プロトコル]]：通信の決まりごと。</li>
<li>[[帯域]]：周波数の範囲。単位は[[ヘルツ（Hz）]]。</li>
</ul>
<p class="note">補足や覚え方をここに書く。</p>` },
  { ch: "1.2", title: "1.2.1 性能", body: `
<div class="formula">距離 ＝ 速さ × 時間</div>
<ol class="flow"><li>要件を決める</li><li>[[見積もる]]</li><li>[[監視する]]</li></ol>` },
]);
